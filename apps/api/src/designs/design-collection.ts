/**
 * The design collection: its shape, and the validation it must pass at startup.
 *
 * The four designs are static data in the repository
 * (`data/designs.v1.ts`). They are checked once, when the application is built,
 * and the process refuses to start if anything is wrong, so a bad design can
 * never be served. See docs/architecture.md, "Design".
 */

import { designSummarySchema, type DesignSummary, type PreviewPath } from '@athar/contracts';
import {
  describeTrajectoryProblems,
  polarSegmentLength,
  type Trajectory,
} from '../device/trajectory.js';
import { distance, largestStep, polarToXY } from './geometry.js';
import { HOME_RHO, HOME_RHO_TOLERANCE } from './home.js';
import { derivePreviewPath } from './preview-path.js';

/** The initial collection has exactly this many designs. */
export const EXPECTED_DESIGN_COUNT = 4;

/**
 * Two consecutive trajectory points may be no further apart than this, in table
 * radii. It keeps every design dense enough for the table's interpolation to
 * reproduce the intended curve, and catches a generator that jumps.
 */
export const MAX_POINT_SPACING = 0.05;

/**
 * Where a segment's length may exceed the straight line between its ends. A
 * curve sampled finely enough is nearly straight between samples; a large ratio
 * means the interpolation would draw something the generator did not intend.
 */
export const MAX_CURVE_TO_CHORD_RATIO = 1.05;

/** What an original modern design's English note must say, per the architecture. */
export const MODERN_INTERPRETATION_PHRASE = 'modern interpretation';

/** A design as written in the data file. */
export interface DesignDefinition extends DesignSummary {
  /** Generated by a pure function, never typed in. API-internal. */
  readonly trajectory: Trajectory;
}

export interface DesignCollectionDefinition {
  readonly collectionVersion: number;
  readonly designs: readonly DesignDefinition[];
}

/** A validated design, ready to serve. */
export interface DesignRecord extends DesignDefinition {
  /** Derived from the trajectory. */
  readonly previewPath: PreviewPath;
}

export interface DesignCollection {
  readonly collectionVersion: number;
  readonly designs: readonly DesignRecord[];
}

/** Everything wrong with the collection, listed at once. */
export class DesignCollectionError extends Error {
  constructor(readonly problems: readonly string[]) {
    super(
      `The design collection is invalid:\n${problems.map((problem) => `  - ${problem}`).join('\n')}`,
    );
    this.name = 'DesignCollectionError';
  }
}

const ARABIC_LETTER = /[؀-ۿ]/;
const LATIN_LETTER = /[A-Za-z]/;

/** Problems with the localized text of one design, as `label: problem` strings. */
function textProblems(design: DesignDefinition): string[] {
  const problems: string[] = [];
  const fields: [string, { en: string; ar: string }][] = [
    ['title', design.title],
    ['description', design.description],
    ['inspiration note', design.inspiration.note],
  ];

  for (const [field, text] of fields) {
    if (!LATIN_LETTER.test(text.en)) {
      problems.push(`${field}.en has no Latin letters (is it in the right language?)`);
    }

    if (!ARABIC_LETTER.test(text.ar)) {
      problems.push(`${field}.ar has no Arabic letters (is it in the right language?)`);
    }
  }

  return problems;
}

/** Problems with how a design describes its inspiration, beyond the shared schema. */
function inspirationProblems(design: DesignDefinition): string[] {
  const { kind, note, sources } = design.inspiration;
  const problems: string[] = [];

  if (kind === 'documented-traditional') {
    if (!sources.some((source) => source.url !== undefined)) {
      problems.push(
        'a documented traditional design needs at least one source with a URL that can be checked',
      );
    }
  } else if (!note.en.toLowerCase().includes(MODERN_INTERPRETATION_PHRASE)) {
    problems.push(
      `an original modern design's English note must say it is a "${MODERN_INTERPRETATION_PHRASE}"`,
    );
  }

  for (const source of sources) {
    if (source.url !== undefined && !source.url.startsWith('https://')) {
      problems.push(`source "${source.label}" must use an https URL`);
    }
  }

  return problems;
}

/**
 * Problems with a trajectory, or none if it can be drawn and chained: the
 * driver's checks, plus starting and ending at home, no jumps and no segment
 * the table's interpolation would bend. Every catalogue design, the rake and
 * every freehand path pass through here.
 */
export function trajectoryProblems(trajectory: Trajectory): string[] {
  const problems = describeTrajectoryProblems(trajectory);

  if (problems.length > 0) {
    return problems;
  }

  const { points } = trajectory;
  const first = points[0];
  const last = points.at(-1);

  if (first === undefined || last === undefined) {
    return ['the trajectory has no points'];
  }

  if (Math.abs(first[1] - HOME_RHO) > HOME_RHO_TOLERANCE) {
    problems.push(`it starts at rho ${first[1]}, not at the home radius ${HOME_RHO}`);
  }

  if (Math.abs(last[1] - HOME_RHO) > HOME_RHO_TOLERANCE) {
    problems.push(`it ends at rho ${last[1]}, not at the home radius ${HOME_RHO}`);
  }

  const spacing = largestStep(points);

  if (spacing > MAX_POINT_SPACING) {
    problems.push(`two points are ${spacing.toFixed(3)} apart; the limit is ${MAX_POINT_SPACING}`);
  }

  for (const [index, point] of points.entries()) {
    const previous = points[index - 1];

    if (previous === undefined) {
      continue;
    }

    const chord = distance(polarToXY(previous), polarToXY(point));

    if (chord > 1e-6 && polarSegmentLength(previous, point) / chord > MAX_CURVE_TO_CHORD_RATIO) {
      problems.push(
        `the segment into point ${index} curves too far from a straight line to be sampled faithfully`,
      );
      break;
    }
  }

  return problems;
}

/**
 * Validate a collection and derive what it needs to be served.
 *
 * Collects every problem before failing, so one run shows them all.
 *
 * @throws DesignCollectionError
 */
export function loadDesignCollection(definition: DesignCollectionDefinition): DesignCollection {
  const problems: string[] = [];

  if (!Number.isInteger(definition.collectionVersion) || definition.collectionVersion < 1) {
    problems.push('collectionVersion must be a positive integer');
  }

  if (definition.designs.length !== EXPECTED_DESIGN_COUNT) {
    problems.push(
      `the collection must contain exactly ${EXPECTED_DESIGN_COUNT} designs, not ${definition.designs.length}`,
    );
  }

  for (const key of ['id', 'slug'] as const) {
    const seen = new Set<string>();

    for (const design of definition.designs) {
      if (seen.has(design[key])) {
        problems.push(`the ${key} "${design[key]}" is used more than once`);
      }

      seen.add(design[key]);
    }
  }

  const records: DesignRecord[] = [];

  for (const design of definition.designs) {
    const label = `design "${design.id}"`;
    const { trajectory, ...summary } = design;
    const parsed = designSummarySchema.safeParse(summary);

    if (!parsed.success) {
      for (const issue of parsed.error.issues) {
        problems.push(`${label}: ${issue.path.join('.') || '(design)'}: ${issue.message}`);
      }
    }

    const own = [
      ...textProblems(design),
      ...inspirationProblems(design),
      ...trajectoryProblems(trajectory).map((problem) => `trajectory: ${problem}`),
    ];

    problems.push(...own.map((problem) => `${label}: ${problem}`));

    if (parsed.success && own.length === 0) {
      try {
        records.push({ ...design, previewPath: derivePreviewPath(trajectory) });
      } catch (error) {
        problems.push(
          `${label}: previewPath could not be derived: ${error instanceof Error ? error.message : String(error)}`,
        );
      }
    }
  }

  if (problems.length > 0) {
    throw new DesignCollectionError(problems);
  }

  return { collectionVersion: definition.collectionVersion, designs: records };
}
